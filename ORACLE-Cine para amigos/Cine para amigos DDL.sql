--------------------------- SESION_USUARIO (Participación) --------------
CREATE TABLE sesion_usuario (
    su_id_sesion_usuario     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    su_id_sesion             NUMBER NOT NULL,
    su_id_usuario            NUMBER NOT NULL,
    su_asistio               NUMBER(1) NOT NULL,
    su_rol_usuario           VARCHAR2(20) NOT NULL,
    
    CONSTRAINT pk_id_sesion_usuario PRIMARY KEY (su_id_sesion_usuario),
    CONSTRAINT fk_sesion_usu_sesion FOREIGN KEY (su_id_sesion) 
        REFERENCES sesion_pelicula(s_id_sesion),
    CONSTRAINT fk_sesion_usu_usuario FOREIGN KEY (su_id_usuario) 
        REFERENCES usuario(u_id_usuario),
    CONSTRAINT uk_sesion_usuario UNIQUE (su_id_sesion, su_id_usuario),
    CONSTRAINT ck_asistio_sesion CHECK (su_asistio IN (0, 1)),
    CONSTRAINT ck_rol_usuario CHECK (su_rol_usuario IN ('ORGANIZADOR', 'ASISTENTE'))
);