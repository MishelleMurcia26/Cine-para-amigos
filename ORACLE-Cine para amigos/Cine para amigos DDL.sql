-- 2. CREACIÓN DE TABLAS Y RESTRICCIONES

--------------------------- USUARIO -------------------------------------
CREATE TABLE usuario (
    u_id_usuario    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    u_nombre        VARCHAR2(100) NOT NULL,
    
    CONSTRAINT pk_id_usuario PRIMARY KEY (u_id_usuario)
);

--------------------------- ORGANIZADOR ---------------------------------
CREATE TABLE organizador (
    o_id_organizador   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    o_nombre           VARCHAR2(100) NOT NULL,
    o_pais_residencia  VARCHAR2(50) NOT NULL,
    
    CONSTRAINT pk_id_organizador PRIMARY KEY (o_id_organizador)
);

--------------------------- PELICULA ------------------------------------
CREATE TABLE pelicula (
    p_id_pelicula         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    p_titulo              VARCHAR2(150) NOT NULL,
    p_genero_principal    VARCHAR2(40) NOT NULL,
    p_anio_estreno        NUMBER(4) NOT NULL,
    p_clasificacion_edad  VARCHAR2(10) NOT NULL,
    
    CONSTRAINT pk_id_pelicula PRIMARY KEY (p_id_pelicula),
    CONSTRAINT ck_anio_estreno_pelicula CHECK (p_anio_estreno BETWEEN 1895 AND 2100),
    CONSTRAINT ck_clasificacion_pelicula CHECK (p_clasificacion_edad IN ('G', 'PG', 'PG-13', 'R', 'NC-17', '+12', '+15', '+18'))
);

--------------------------- PLATAFORMA ----------------------------------
CREATE TABLE plataforma (
    pl_id_plataforma               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pl_nombre_plataforma           VARCHAR2(50) NOT NULL,
    pl_permite_trans_llamada       NUMBER(1) NOT NULL,
    
    CONSTRAINT pk_id_plataforma PRIMARY KEY (pl_id_plataforma),
    CONSTRAINT ck_permite_trans_llamada CHECK (pl_permite_trans_llamada IN (0, 1))
);

--------------------------- SESION_PELICULA  --------------------
CREATE TABLE sesion_pelicula (
    s_id_sesion              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    s_id_organizador         NUMBER NOT NULL,
    s_id_pelicula            NUMBER NOT NULL,
    s_id_plataforma_streaming NUMBER NOT NULL,
    s_fecha_evento           DATE NOT NULL,
    s_duracion_minutos       NUMBER NOT NULL,
    s_tipo_audiencia         VARCHAR2(30) NOT NULL,
    
    CONSTRAINT pk_id_sesion PRIMARY KEY (s_id_sesion),
    CONSTRAINT fk_sesion_organizador FOREIGN KEY (s_id_organizador) 
        REFERENCES organizador(o_id_organizador),
    CONSTRAINT fk_sesion_pelicula FOREIGN KEY (s_id_pelicula) 
        REFERENCES pelicula(p_id_pelicula),
    CONSTRAINT fk_sesion_plataforma FOREIGN KEY (s_id_plataforma_streaming) 
        REFERENCES plataforma(pl_id_plataforma),
    CONSTRAINT ck_duracion_minutos CHECK (s_duracion_minutos > 0),
    CONSTRAINT ck_tipo_audiencia CHECK (s_tipo_audiencia IN ('AMIGOS', 'FAMILIA', 'COMPAÑEROS', 'OTRO'))
);

